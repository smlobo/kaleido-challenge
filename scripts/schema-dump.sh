#!/usr/bin/env bash
# Regenerates docs/schema.sql: the database schema as it stands after every
# migration in internal/db/migrations, one CREATE statement per table, for
# reading. The migrations stay the source of truth; run this after adding one.
#
# It applies the migrations to a throwaway schema in the docker compose
# Postgres, dumps that schema with the server's own pg_dump, and drops it.
# Nothing else in the database is touched.
#
#   scripts/schema-dump.sh
set -euo pipefail

cd "$(dirname "$0")/.."
compose=(docker compose -f docker/docker-compose.yaml exec -T postgres)
psql=("${compose[@]}" psql -X -q -v ON_ERROR_STOP=1 -U ticketing -d ticketing)
tmp="schema_dump" # fixed, so its name can be stripped from the output

cleanup() { "${psql[@]}" -c "DROP SCHEMA IF EXISTS $tmp CASCADE" >/dev/null 2>&1 || true; }
trap cleanup EXIT

"${psql[@]}" -c "CREATE SCHEMA $tmp"
for f in internal/db/migrations/*.sql; do
	{ echo "SET search_path TO $tmp;"; cat "$f"; } | "${psql[@]}" -1 >/dev/null
done

{
	cat <<'EOF'
-- GENERATED by scripts/schema-dump.sh. Do not edit, and do not apply it:
-- the migrations in internal/db/migrations are the source of truth. This is
-- the schema they produce, all in one place, for reading.
EOF
	"${compose[@]}" pg_dump -U ticketing -d ticketing --schema-only --no-owner --no-privileges \
		--no-comments -n "$tmp" |
		# Drop pg_dump's session settings, its comment banners and the
		# throwaway schema's name.
		grep -vE '^(SET |SELECT pg_catalog\.set_config|CREATE SCHEMA |\\(un)?restrict |--)' |
		sed -e "s/$tmp\.//g" |
		cat -s
} >docs/schema.sql

echo "wrote docs/schema.sql ($(grep -c '^CREATE TABLE' docs/schema.sql) tables)"
